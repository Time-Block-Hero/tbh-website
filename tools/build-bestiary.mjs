import fs from 'node:fs';
import {createHash} from 'node:crypto';
import vm from 'node:vm';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const context={window:{}};
for(const file of ['bestiary-data.js','bestiary-taxonomy.js'])vm.runInNewContext(fs.readFileSync(path.join(root,file),'utf8'),context);
const data=JSON.parse(fs.readFileSync(path.join(root,'data/cards.json'),'utf8'));
const result={};
for(const entry of context.window.TBH_BESTIARY_CATALOG.entries){
 for(const key of entry.sourceArtworkKeys||[]){
  const matches=data.cards.filter(c=>c.artworkKey===key);
  if(matches.length!==1)throw new Error(`Unresolved bestiary identity: ${key}`);
  const c=matches[0],variants=data.artworkVariants[c.id]||[],selected=variants.find(v=>v.id===data.selectedArtworkIds[c.id]);
  if(data.selectedArtworkIds[c.id]&&!selected)throw new Error(`Missing selected artwork: ${key}`);
  result[key]={key,name:c.nameKey,enName:c.englishName,description:c.artDescription,descriptionHash:createHash('sha256').update(c.artDescription).digest('hex'),image:selected?.src||null};
 }
}
fs.writeFileSync(path.join(root,'bestiary-card-sources.js'),'// Generated by tools/build-bestiary.mjs; do not edit.\nwindow.TBH_BESTIARY_CARD_SOURCES = '+JSON.stringify(result,null,2)+';\n');
console.log(`Built ${Object.keys(result).length} bestiary card references.`);
