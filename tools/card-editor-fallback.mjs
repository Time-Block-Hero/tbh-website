import fs from "node:fs";
import path from "node:path";

// Shared by the offline build and project-save transaction.
export function buildEditorFallback(root, cards, layout) {
  const manifestPath = path.join(root, "data/card-standees.json");
  const standees = fs.existsSync(manifestPath)
    ? JSON.parse(fs.readFileSync(manifestPath, "utf8"))
    : { schemaVersion: 1, source: null, entries: [] };
  return `/* Generated by tools/build-card-editor-fallback.mjs. */\nwindow.__CARD_EDITOR_FALLBACK__ = ${JSON.stringify({ cards, layout, standees })};\n`;
}
